function DotChar({
  char,
  dotSize = 5,
  gap = 3,
  bright = true,
  blink = false,
}: {
  char: string;
  dotSize?: number;
  gap?: number;
  bright?: boolean;
  blink?: boolean;
}) {
  const isColon = char === ":";
  const grid = PATTERNS[char];
  if (!grid) return null;

  return (
    <div
      className="grid"
      style={{
        gridTemplateColumns: `repeat(5, ${dotSize}px)`,
        gridTemplateRows: `repeat(7, ${dotSize}px)`,
        gap: `${gap}px`,
      }}
    >
      {grid.flat().map((on, i) => (
        <div
          key={i}
          className={blink && isColon ? "animate-pulse" : ""}
          style={{
            width: dotSize,
            height: dotSize,
            borderRadius: 1,
            backgroundColor: on
              ? bright
                ? "rgba(255,255,255,0.98)"
                : "rgba(255,255,255,0.4)"
              : "transparent",
          }}
        />
      ))}
    </div>
  );
}

interface DotMatrixTextProps {
  text: string;
  dotSize?: number;
  gap?: number;
  charGap?: number;
  className?: string;
  blinkColon?: boolean;
}

export function DotMatrixText({
  text,
  dotSize = 5,
  gap = 3,
  charGap = 14,
  className = "",
  blinkColon = false,
}: DotMatrixTextProps) {
  return (
    <div className={`flex items-center ${className}`} style={{ gap: charGap }}>
      {text.split("").map((char, i) => (
        <DotChar
          key={`${char}-${i}`}
          char={char}
          dotSize={dotSize}
          gap={gap}
          blink={blinkColon && char === ":"}
        />
      ))}
    </div>
  );
}
